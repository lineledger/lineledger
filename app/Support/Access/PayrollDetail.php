<?php

namespace App\Support\Access;

use App\Models\JournalEntry;
use App\Models\PayrollCheque;
use App\Models\PayrollRemittance;
use App\Models\PayRun;
use ArrayObject;
use Illuminate\Database\Eloquent\Builder as EloquentBuilder;
use Illuminate\Database\Query\Builder as QueryBuilder;

/**
 * Payroll detail on the general ledger — the employee on a payroll cheque or a
 * net-pay line, its memo, the link through to the pay run — is shown only to
 * members who can open pay runs (PermissionSet::seesPayrollDetail()). Everyone
 * else who reads the ledger (the journal, the general ledger, the
 * transactions report, the bank register) sees such lines as "Payroll", with
 * no name and no link. Amounts stay, so balances and totals still foot.
 *
 * A payroll entry is one generated by a pay run, payroll cheque or remittance,
 * or the reversal that voids one: a void copies every line's memo and
 * employee, but carries no source of its own, only reverses_entry_id.
 */
final class PayrollDetail
{
    /** @var list<class-string> journal-entry sources that carry payroll detail */
    public const SOURCES = [PayRun::class, PayrollCheque::class, PayrollRemittance::class];

    /** Container key of the per-request memo of reversed entries' sources. */
    private const REVERSED_SOURCES = 'payroll-detail.reversed-sources';

    public static function isPayroll(?string $sourceType): bool
    {
        return $sourceType !== null && in_array($sourceType, self::SOURCES, true);
    }

    /**
     * Whether a line from this source must be shown without its detail.
     */
    public static function hides(?string $sourceType, PermissionSet $viewer): bool
    {
        return self::isPayroll($sourceType) && ! $viewer->seesPayrollDetail();
    }

    /**
     * Whether the entry's detail must be withheld from the viewer: it is a
     * payroll entry, or reverses one, and the viewer can't open pay runs.
     */
    public static function hidesEntry(?JournalEntry $entry, PermissionSet $viewer): bool
    {
        return $entry !== null && ! $viewer->seesPayrollDetail() && self::isPayroll(self::sourceTypeOf($entry));
    }

    /**
     * The entry's own source type or, for a reversal with none of its own,
     * the source type of the entry it reverses. One query per reversed entry,
     * memoised for the request (scoped, so a queue worker doesn't carry it
     * from one job to the next).
     */
    public static function sourceTypeOf(JournalEntry $entry): ?string
    {
        if ($entry->source_type !== null || $entry->reverses_entry_id === null) {
            return $entry->source_type;
        }

        app()->scopedIf(self::REVERSED_SOURCES, fn () => new ArrayObject);

        /** @var ArrayObject<int, ?string> $memo */
        $memo = app(self::REVERSED_SOURCES);
        $id = (int) $entry->reverses_entry_id;

        if (! $memo->offsetExists($id)) {
            $memo[$id] = JournalEntry::query()->whereKey($id)->value('source_type');
        }

        return $memo[$id];
    }

    /**
     * Narrow a query on journal entries ($table, or its alias) to those that
     * aren't payroll: no payroll source of their own, and not the reversal of
     * an entry that has one. The subquery keeps the company scope.
     *
     * @template TBuilder of EloquentBuilder<*>|QueryBuilder
     *
     * @param  TBuilder  $query
     * @return TBuilder
     */
    public static function withoutPayroll(EloquentBuilder|QueryBuilder $query, string $table = 'journal_entries'): EloquentBuilder|QueryBuilder
    {
        return $query
            ->where(fn ($w) => $w
                ->whereNull("{$table}.source_type")
                ->orWhereNotIn("{$table}.source_type", self::SOURCES))
            ->where(fn ($w) => $w
                ->whereNull("{$table}.reverses_entry_id")
                ->orWhereNotIn("{$table}.reverses_entry_id", JournalEntry::query()->select('id')->whereIn('source_type', self::SOURCES)));
    }

    /**
     * What a hidden payroll line shows instead of its memo or name.
     */
    public static function label(): string
    {
        return __('Payroll');
    }
}
